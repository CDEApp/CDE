using System;
using System.Globalization;
using System.Text;

namespace cdeMemProbe;

/// <summary>Renders <see cref="PerfReport"/> as Markdown, and refreshes the generated block in the Readme.</summary>
public static class PerfMarkdown
{
    public const string BeginMarker = "<!-- perf-table:begin -->";
    public const string EndMarker = "<!-- perf-table:end -->";

    public static string ReadmeBlock(PerfReport r)
    {
        var sb = new StringBuilder();
        sb.AppendLine(BeginMarker);
        sb.AppendLine("<!-- Generated by `cdeMemProbe --readme`; do not edit by hand. -->");
        sb.AppendLine();
        sb.AppendLine(Description(r));
        sb.AppendLine();
        sb.AppendLine("| Metric | Value |");
        sb.AppendLine("| ------ | ----: |");
        sb.AppendLine($"| `.cdex` size | {Bytes(r.CdexBytes)} |");
        sb.AppendLine($"| Scan time | {(r.ScanMs is { } s ? Ms(s) : "n/a (written directly)")} |");
        sb.AppendLine($"| Peak RSS (search, mmap) | {Bytes(r.PeakRssBytes)} |");
        foreach (var q in r.Queries)
        {
            sb.AppendLine($"| {q.Name} search, cold / warm | {Ms(q.ColdMs)} / {Ms(q.WarmMedianMs)} |");
        }

        sb.AppendLine();
        sb.AppendLine(r.ScanMs is null
            ? "Scan time is n/a for this fixture: the `.cdex` was written directly from the synthetic tree, not by `cde scan`."
            : "Scan time is the wall time of a real `cde scan` over a directory tree of empty files.");
        if (!r.ColdCacheDropped)
            sb.AppendLine("The page cache could not be dropped, so the cold numbers are not truly cold.");
        sb.Append(EndMarker);
        return sb.ToString();
    }

    public static string SummaryTable(PerfReport r, ComparisonResult cmp)
    {
        var sb = new StringBuilder();
        sb.AppendLine("## Performance");
        sb.AppendLine();
        sb.AppendLine(Description(r));
        sb.AppendLine();
        sb.AppendLine("### Change vs previous release");
        if (cmp.Note is not null) sb.AppendLine(cmp.Note);
        sb.AppendLine();
        sb.AppendLine("| Metric | Baseline | Current | Change | Status |");
        sb.AppendLine("| ------ | -------: | ------: | -----: | ------ |");
        foreach (var d in cmp.Deltas)
        {
            var pct = d.PercentChange is { } p ? p.ToString("+0.0;-0.0;0.0", CultureInfo.InvariantCulture) + "%" : "n/a";
            var status = d.Severity switch
            {
                DeltaSeverity.Fail => "FAIL",
                DeltaSeverity.Warn => "warn",
                _ => "ok",
            };
            var baseline = d.Baseline is { } b ? b.ToString("N0", CultureInfo.InvariantCulture) : "n/a";
            sb.AppendLine($"| {d.Metric} | {baseline} | {d.Current.ToString("N0", CultureInfo.InvariantCulture)} | {pct} | {status} |");
        }

        return sb.ToString();
    }

    /// <summary>Replaces the text between the markers (inclusive) with <paramref name="block"/>.</summary>
    public static string ReplaceBlock(string readme, string block)
    {
        var begin = readme.IndexOf(BeginMarker, StringComparison.Ordinal);
        var end = readme.IndexOf(EndMarker, StringComparison.Ordinal);
        if (begin < 0 || end < begin)
            throw new InvalidOperationException($"Readme must contain {BeginMarker} followed by {EndMarker}.");
        return string.Concat(readme.AsSpan(0, begin), block, readme.AsSpan(end + EndMarker.Length));
    }

    private static string Description(PerfReport r) =>
        $"Measured on a GitHub ubuntu runner ({r.Os}) at commit `{Short(r.Commit)}`, " +
        $"{r.FixtureEntries.ToString("N0", CultureInfo.InvariantCulture)} synthetic entries (seed {r.Seed}), " +
        "mmap `.cdex` path.";

    private static string Short(string commit) => commit.Length > 8 ? commit[..8] : commit;

    private static string Ms(double ms) => ms.ToString("N1", CultureInfo.InvariantCulture) + " ms";

    private static string Bytes(long b) =>
        b >= 1L << 30 ? (b / (double)(1L << 30)).ToString("N2", CultureInfo.InvariantCulture) + " GB"
        : (b / (double)(1L << 20)).ToString("N1", CultureInfo.InvariantCulture) + " MB";
}
